/* ------------------------------ Helpers ------------------------------ */
const todayStr = () => {
  const d = new Date();
  const yyyy = d.getFullYear();
  const mm = `${d.getMonth() + 1}`.padStart(2, "0");
  const dd = `${d.getDate()}`.padStart(2, "0");
  return `${yyyy}-${mm}-${dd}`;
};

const normalizeDomain = (d: string) => d.trim().toLowerCase().replace(/^https?:\/\//i, "").replace(/^www\./i, "").replace(/\/+$/, "");

const isSubdomainOf = (host: string, root: string) => host === root || host.endsWith("." + root);

const safeHostname = (raw?: string) => {
  if (!raw) return "";
  try {
    const u = new URL(raw);
    return normalizeDomain(u.hostname);
  } catch {
    // Raw may already be a hostname — try to treat as host
    return normalizeDomain(raw);
  }
};

const buildFilename = (primaryDomain?: string) => `${normalizeDomain(primaryDomain || "your-domain")}-disavow-${todayStr()}.txt`;

const buildGscDisavowUrl = (prop: GSCProperty) => {
  const base = "https://search.google.com/search-console/disavow-links";
  if (prop.type === "domain") {
    const dom = normalizeDomain(prop.property);
    return `${base}?resource_id=sc-domain:${encodeURIComponent(dom)}`;
  }
  const site = prop.property.replace(/\/+$/, "");
  return `${base}?resource_id=sc-site:${encodeURIComponent(site)}`;
};

/** Compose .txt content in Google's supported format */
const buildTxt = (items: ActiveDisavowItem[], primaryDomain?: string) => {
  const domains = new Set<string>();
  const urls: string[] = [];

  for (const it of items) {
    if (it.type === "Domain") domains.add(normalizeDomain(it.domain));
    if (it.type === "URL" && it.url) urls.push(it.url);
  }

  // Filter URLs covered by domain-level entries
  const filteredUrls = urls.filter((u) => {
    const host = safeHostname(u);
    if (!host) return false;
    for (const d of domains) {
      if (isSubdomainOf(host, d)) return false;
    }
    return true;
  });

  const domainLines = Array.from(domains).sort().map((d) => `domain:${d}`);
  const urlLines = Array.from(new Set(filteredUrls)).sort().map((u) => `url:${u}`);

  const header = [
    `# Disavow file generated by Wranker`,
    `# Project: ${normalizeDomain(primaryDomain || "your-domain")}`,
    `# Date: ${todayStr()}`,
    `# One entry per line. Use domain:example.com for domain-wide disavow.`,
    ``,
  ].join("\n");

  return [header, ...domainLines, ...urlLines].join("\n");
};

const downloadTxt = (filename: string, content: string) => {
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
};

/* ------------------------------ Small UI ------------------------------ */
function SplitButton({
  label,
  onPrimary,
  items,
  title,
}: {
  label: string;
  onPrimary: () => void;
  items: { label: string; onClick: () => void }[];
  title?: string;
}) {
  const [open, setOpen] = useState(false);
  const ref = useRef<HTMLDivElement | null>(null);
  useEffect(() => {
    const onDoc = (e: MouseEvent) => {
      if (!ref.current) return;
      if (!ref.current.contains(e.target as Node)) setOpen(false);
    };
    document.addEventListener("mousedown", onDoc);
    return () => document.removeEventListener("mousedown", onDoc);
  }, []);
  return (
    <div ref={ref} className="relative inline-flex">
      <button
        type="button"
        onClick={onPrimary}
        title={title}
        className="inline-flex items-center gap-2 rounded-l-full border-y border-l px-3 py-1.5 text-sm hover:bg-gray-50"
        style={{ borderColor: TK.border, cursor: "pointer" }}
      >
        <Download size={16} color={TK.brand} />
        {label}
      </button>
      <button
        type="button"
        onClick={() => setOpen((s) => !s)}
        className="rounded-r-full border px-2 py-1.5 hover:bg-gray-50"
        style={{ borderColor: TK.border, cursor: "pointer" }}
        aria-haspopup="menu"
        aria-expanded={open}
      >
        <ChevronDown size={16} />
      </button>
      {open && (
        <div
          role="menu"
          className="absolute right-0 top-[110%] z-50 min-w-[180px] rounded-md border bg-white p-1 shadow"
          style={{ borderColor: TK.border }}
        >
          {items.map((it) => (
            <button
              key={it.label}
              type="button"
              onClick={it.onClick}
              className="flex w-full items-center justify-between rounded px-2 py-1.5 text-sm hover:bg-[#F7FAFC]"
              style={{ cursor: "pointer" }}
              role="menuitem"
            >
              <span className="inline-flex items-center gap-2">
                <Download size={14} color={TK.brand} /> {it.label}
              </span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

